#!/usr/bin/env node
// Inlines the widget sources (src/ui/{board,card,figures}/*, src/ui/debug.js) into
// src/ui/generated/widgets.ts, so each widget ships as ONE self-contained HTML string while
// its CSS/JS stay real, lintable files (#271). The runtime never touches the filesystem.
//
//   node scripts/gen-widgets.mjs           # rewrite src/ui/generated/widgets.ts
//   node scripts/gen-widgets.mjs --check   # exit 1 if the checked-in output is stale
//
// Source syntax:
//   {{include file}}   replaced by that file's content (path relative to the including file)
//   /*@ … @*/ or <!--@ … @-->  a leading source-only header, dropped from the output
// Runtime placeholders (__TOOL__, __VERSION__, __VARIANT__, __DEBUG__) pass through untouched;
// the *-html.ts modules fill them per render.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const UI = path.join(root, "src", "ui");
const OUT = path.join(UI, "generated", "widgets.ts");
const check = process.argv.includes("--check");

// Export name → entry file under src/ui/.
const ENTRIES = [
  ["BOARD_TEMPLATE", "board/board.html"],
  ["CARD_TEMPLATE", "card/card.html"],
  ["FIGURES_TEMPLATE", "figures/figures.html"],
  ["DEBUG_JS", "debug.js"],
];

const HEADER = /^(?:\/\*@[\s\S]*?@\*\/|<!--@[\s\S]*?@-->)\n/;
const INCLUDE = /\{\{include ([\w./-]+)\}\}/g;

function fail(msg) {
  process.stderr.write(`gen-widgets: ${msg}\n`);
  process.exit(1);
}

/** File content with its source header dropped and every include resolved (cycle-safe). */
function assemble(file, stack = []) {
  if (stack.includes(file)) fail(`include cycle: ${[...stack, file].join(" -> ")}`);
  if (!existsSync(file)) fail(`missing include ${path.relative(root, file)}`);
  const body = readFileSync(file, "utf8").replace(HEADER, "");
  return body.replace(INCLUDE, (_, rel) => assemble(path.join(path.dirname(file), rel), [...stack, file]));
}

const lines = [
  "// GENERATED by scripts/gen-widgets.mjs from src/ui/{board,card,figures}/* and src/ui/debug.js — do not edit.",
  "// Regenerate with `pnpm widgets`; CI fails on drift (`pnpm widgets:check`).",
  "",
];
for (const [name, entry] of ENTRIES) {
  lines.push(
    `/** Inlined from src/ui/${entry}. */`,
    `export const ${name} = ${JSON.stringify(assemble(path.join(UI, entry)))};`,
  );
}
const next = lines.join("\n") + "\n";

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== next) fail("src/ui/generated/widgets.ts is stale — run `pnpm widgets` and commit it.");
} else if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== next) {
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, next);
}
